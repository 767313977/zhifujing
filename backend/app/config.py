    # 也不会过期，配上它之后 lark_cli 那条路就不会再走。
    feishu_webhook_url: str = ""
    # 备用通道的收件人：ou_ 开头=用户 open_id（自己给自己发），oc_ 开头=会话 id。
    # 只在没配 webhook 时生效。
    feishu_target: str = ""
    feishu_push_enabled: bool = True
    # Trae 插件自带的命令行工具，默认在 PATH 上
    lark_cli: str = "lark-cli"

    # --- 形态选股：股票池与日线 ---
    # 池子门槛：近 20 日日均成交额（元）。低于这个数的票出了形态也没法交易，
    # 采它们的日线纯属白花 iFinD 配额。
    # 2026-09-25 用户要求从 1 亿降到 **2000 万**：把日均成交额 2000 万~1 亿的
    # 中小盘票也纳入形态扫描。代价是池子从约 3066 只涨到约 5278 只，新进约 2200 只
    # 票没有历史日线，需要历史回补慢慢铺（每天 4 个交易日 × 14 次调用），
    # 铺满前这些票在形态扫描里会因根数不足被跳过。
    #
    # 2026-09-26 实际重建：**5288 只**（与上面预估的 5278 吻合），用户确认维持此门槛。
    # ⚠️ 池子大小**不影响每日采集配额** —— 日线采集是按代码前缀问全市场、一天 13 次
    # （见 `collect_kline._fetch_day`），与池子里有多少只无关。别再把「池子变大」
    # 和「调用变多」画等号（曾经这么以为过，是错的）。
    universe_min_amount: float = 2e7
    # 日线采集的批次大小**不再是配置项**：现在按「代码前缀 × 单个交易日」问，
    # 一天一个前缀一次调用（13 次覆盖全市场），没有可调的批大小。
    # 历史上这里有个 kline_batch_size=50，配合「50 只 × 一段区间」的批量行情接口 ——
    # 那个接口 2026-09-21 起不再提供 CSV，超过 100 行会静默返回抽样表，已弃用。
    # 首次建库拉多少个交易日的历史。
    # 2026-09-21 从 250 提到 **500（约 2 年）**：个股页的周/月 K 按 2 年画，
    # 而这个窗口也是「历史回补」的边界（`_window_start(full=True)` 用它）。
    # ⚠️ 一个完整窗口 ≈ 500 天 × 14 次 = 7000 次调用 —— 按当前口径（9000，2026-09-28）
    # 占掉 **78%**，一次拉完会直接顶到 80% 那条让路线、把当天的采集停掉。所以必须靠
    # 下面的 `kline_backfill_days` 每天往前啃一小段，见 scheduler。
    kline_history_days: int = 500
    # 每日增量回看的**日历日**跨度（留宽一点，覆盖最近几个交易日并容忍假期）。
    # 现在的作用是「顺带回补最近这些天里还缺数据的日子」。
    kline_refresh_calendar_days: int = 12
    # 每天自动往前啃几个交易日的历史（每个交易日 = 14 次调用）。
    # 4 天 ≈ 56 次/天 ≈ 1700 次/月，配上日常采集约 2100 次 ≈ 3800 次，占当前口径
    # （9000）的四成出头。⚠️ 「1700 + 2100」这两个数写于口径还是 7000 的时候，那时
    # 算「正好压在配额里」；现在余量更宽，但**先别急着加天数** —— 这个值同时决定
    # 铺满 500 天要多久，按 4 天/天从 250 天铺到 500 天约 2 个月。
    kline_backfill_days: int = 4
    # 历史回补的**停手线**（用量占配额的比例）。
    # 特意比日线采集的让路线（80%，见 usage.QuotaLevel）更保守：这样
    # **回补永远不会把当天的日线采集顶停** —— 历史是慢慢补的，而当天的行情
    # 缺了就真缺了（数据源只保留最近 15 个交易日）。
    kline_backfill_max_ratio: float = 0.74
    # stock_daily 保留的交易日数。
    #
    # 形态最长看 250 日，而**周/月 K 是按需拉 2 年历史的**（打开个股页切到
    # 周/月时，前端会调一次 `sync?days=500`，约 500 个交易日 ≈ 24 个月）。
    # 这个值必须 ≥ 500，否则拉回来的历史会被 `prune()` 当晚剪掉最老的一段，
    # 白花那十几次 iFinD 调用。520 是 500 + 一点余量。
    kline_keep_days: int = 520

    # ---- 每日「命中前 N 只」的 DDE 补齐（2026-09-26 用户要求）----
    #
    # 形态扫描出结果后，把当天命中列表里**评分最高的 N 只**的 DDE 补到最近
    # `dde_hit_days` 个交易日 —— 这几只才是当天真正要看的票，而全市场扫描那条路
    # 每天只写当天一行（`scan_dde` 与请求日期无关）。
    #
    # 成本 = N 次 iFinD 调用/交易日：50 只 ≈ 1100 次/月，约占一个周期额度（9000）
    # 的 12%。所以它与全市场扫描共用同一道让路线（用量 80% 时先停它）。
    # 调大就是覆盖更全、更贵；调小则页面上那几只票的 DDE 栏会短一截。
    dde_hit_top_n: int = 50
    # 补多长的窗口：与个股页 DDE 一栏的默认天数一致（60 ≈ 一个季度，够看趋势）
    dde_hit_days: int = 60

    # ---- 每日「命中前 N 只」的**日线**补齐（2026-10-09 用户要求）----
    #
    # 形态扫描出结果后，把当天命中列表里**评分最高的 N 只**的日线补到**最近交易日**
    # （`scan_patterns.backfill_top_kline`）。为什么要有：形态页那张 K 线读的就是
    # `stock_daily`，某只的最后一根早于最近交易日，图上最新几天就是断的。
    #
    # 与上面 DDE 那一步的区别：它**走免费源为主**（东财 → 腾讯，iFinD 只兜底），
    # 常态零 iFinD 配额 —— 所以**不设让路阈值**，配额紧张时也照跑。
    # 口径与页面「评分前 50」一致（`collect_dde.top_hit_codes`）。
    kline_hit_top_n: int = 50

    # ---- 「胜率跟踪」页的统计起点（2026-09-27 用户要求「每个循环从 9 月 24 日开始统计」）----
    #
    # 从这一天起，每个有命中记录的交易日就是一个「循环」，往后跟 30 个交易日。
    # 为什么要有起点：09-24 之前那几天只扫了 3032 只（当天起才扩到 5279 只），
    # 「前 50 只」是在不同大小的池子里排出来的，前后不可比。
    #
    # 做成配置是**为了不用改代码就能挪**（比如攒够一段之后想从 10-01 重新开始）。
    # ⚠️ 往里挪（更晚）只是不显示更早的循环；往外挪（更早）会把不可比的老数据放进来。
    pattern_track_start: date = date(2026, 9, 24)

    # ---- 悟道池子「成绩单」的统计起点 ----
    #
    # 悟道六池（明天盯 / 明天预案 / 洗完可盯 / 华宝早期 / 洗后可盯 / 缩量洗盘中）单独做
    # 一份按池子的跟踪。**起点必须是一段「同一套候选口径」的日子**。
    #
    # 2026-10-09：先把 09-10 ~ 10-08 这 15 个交易日**用当前判定整个重扫了一遍**
    # （`POST /api/admin/patterns/scan?date=...`，幂等、零配额，见设计文档 §8.87.4），
    # 所以从 **09-10** 起所有命中都是同一套口径（含候选池与板块范围），统计可比。
    # ⚠️ 09-10 之前那些天的命中还是**旧口径**留下的，别把起点往前挪 ——
    # 要用更早的日子，先把它们也重扫一遍。
    pool_track_start: date = date(2026, 9, 10)


