    #   悟道本地库 → 东财 → 腾讯 → iFinD
    # 云端没有悟道库、又连不上东财直连，所以前两级都落空 —— 腾讯那级就是为云端加的
    # （国内机房可达、不占配额），加上它之后 iFinD 那一级基本不再被用到。
    #
    # **东财熔断**：连续失败这么多次就本轮不再试它。不熔断的代价是**逐只等约 10 秒超时** ——
    # 实测 2026-09-24：48 只候选在上面白等约 8 分钟（这也就是那天简报 17:23 才发出的原因）。
    wudao_em_breaker_failures: int = 3
    # **腾讯熔断**：同理。这条线整轮不通时（接口变动 / 该机器不可达），
    # 不熔断就是 48 只 × 两次请求，每只都要等到超时。
    wudao_tx_breaker_failures: int = 3
    # **iFinD 兜底上限**：每轮最多补几只（每只 1 次调用）。实测 09-24 需要补 48 只 = 48 次调用，
