    # 而「复盘找主线」要的恰恰是后者。反过来 `仪器仪表`（52 只）、`培育钻石`（18 只）
    # 这类精准板块根本挤不进榜。
    #
    # 阈值取 1000 是**看分布定的**（精选 258 个有净额的板块，成分股数中位数只有 85 只、
    # 75 分位 273、90 分位 664 —— 宽泛的那批是尾部少数；用户选的也是「最保守」这档）：
