# ---------------------------------------------------------------- 复权


#: 一行日线要能当「一根 K 线」用，这几个字段都必须有值。
#: iFinD 对停牌日会给一行「只有收盘价、其余全空」的**残行**，`build_bars` 里
#: `float(r["open"])` 遇到它直接抛 `TypeError`（`float(None)` 不行）。
BAR_REQUIRED_FIELDS = ("open", "high", "low", "close", "pct_chg")


def usable_bar(bar: dict) -> bool:
    """一行日线能不能当一根 K 线用：`BAR_REQUIRED_FIELDS` 五项都要非空。

    2026-10-10 从 `services.stock_phase.load_phase` 抽成公共函数，供三处共用
    （`scan_patterns._load_bars` / `scripts.backtest_patterns._load_history` /
    `stock_phase.load_phase`）—— 原来那两处只滤 `close / pct_chg` 两项，遇到
    「收盘价有值、开高低为空」的残行会把 `None` 喂进 `build_bars`，整轮扫描崩掉；
    `load_phase` 那一处本来就滤了五项（注释写明「`float(None)` 会直接抛 500」），
    以它为准统一。调用方要先把自己的行**转成 dict** 再传进来。
    """
    return all(bar.get(field) is not None for field in BAR_REQUIRED_FIELDS)


def build_bars(records: list[dict]) -> Bars:
    """把一只票的**不复权**日线记录转成前复权序列。

    `records` 必须按交易日升序，每项含 `date / open / high / low / close /
    volume / amount / pct_chg`（值为 None 的请调用方先过滤掉）。

    ## 为什么用涨跌幅而不是「前复权价」

    iFinD 不给前复权价，但 `涨跌幅` 是**已按除权调整的真实收益率**（实测验证过
    21 个银行除权日）。所以：

    - 收盘序列：`net[i] = net[i-1] * (1 + pct[i]/100)`，即真实收益的复利
    - 当日 OHLC：用**当天收盘价**做基准换算 —— `adj_x[i] = x[i] * net[i] / close[i]`

    第二步只能按天内的比例换算，不能乘一个累计因子。因为除权调整发生在
    当日开盘相对昨日收盘之间，**同一根 K 线内部的四个价格本来就在同一个基准上**；
    乘累计因子会把整根 K 线一起挪走，反而制造出一个假的跳空。

    锚点取「最新一根的收盘价」：前复权的通行定义就是以最新价为基准，
    这样最近的关键位（突破价等）可以直接当作真实价格看。

    ## 成交量也要按同一比例缩放

    ⚠️ 价格前复权了、量却用原始值，会让「量比」在送转之后整体虚高（10 转 10 约翻倍），
    凭空触发放量类形态、又把缩量类压掉（2026-10-10 修）。除权日股本变了，绝对量本来就
    不该直接跨日比。做法与个股接口 `_adjusted(vol_adjust=True)` 同一口径：
    **量 ÷ (复权价 / 原始价)**（= `volume / ratio`）—— 除权日之后复权价相对原始价缩小，
    量相应放大，跨除权日才可比。成交额 `amount` **不缩放**（钱是钱，与接口一致）。
    """
    if not records:
        raise ValueError("build_bars 收到空序列")

    close = np.array([float(r["close"]) for r in records], dtype=float)
    pct = np.array([float(r["pct_chg"] or 0.0) for r in records], dtype=float)

    # 首日没有涨跌幅，净值从 1 起算
    net = np.empty(len(records), dtype=float)
    net[0] = 1.0
    if len(records) > 1:
        net[1:] = np.cumprod(1.0 + pct[1:] / 100.0)
    # 锚到最新价：adj[-1] == 原始收盘价
    net *= close[-1] / net[-1]

    # 日内比例换算。close 理论上不会为 0，真出现就整根丢掉意义，直接置 1 避免除零
    ratio = np.divide(net, close, out=np.ones_like(net), where=close != 0)
    # 成交量按同一比例**反向**缩放（见 docstring）。ratio 为 0 是病态数据，退回 1 别除爆
    volume_ratio = np.where(ratio != 0, ratio, 1.0)

    return Bars(
        dates=[r["date"] for r in records],
        open=np.array([float(r["open"]) for r in records]) * ratio,
        high=np.array([float(r["high"]) for r in records]) * ratio,
        low=np.array([float(r["low"]) for r in records]) * ratio,
        close=net,
        volume=np.array([float(r["volume"] or 0.0) for r in records]) / volume_ratio,
        amount=np.array([float(r["amount"] or 0.0) for r in records]),
        pct_chg=pct,
    )


# ---------------------------------------------------------------- 打分工具


def _gate_score(value: float, gate: float, ideal: float) -> float:
    """「过了门槛就给分，到理想值满分」的线性映射，方向由 `gate` 与 `ideal` 的大小决定。

    - `ideal < gate`：越小越好（缩量幅度、回撤深度、两底差距…）
    - `ideal > gate`：越大越好（恢复比例、收回力度…）

    和 `_band_score` 的分工：有两个方向都扣分的用 `_band_score`（乖离率、放量倍数
    —— 太弱不行、太强也不行）；只有一个方向的用这个。

    **不要把 `gate` 当成满分点**：那样刚过门槛的样本会直接拿 0 分，等于把
    「能接受的最差值」和「理想值」混成一件事。实测这么写会让一个形态的命中
    从 80 只掉到 16 只（当时测的是「回踩不破」，该形态 2026-09-27 已删）——
    分数低到进不了库，而不是判定变严了。
    """
    if gate == ideal:
        return 1.0
    if ideal < gate:  # 越小越好
        if value >= gate:
            return 0.0
        if value <= ideal:
            return 1.0
        return (gate - value) / (gate - ideal)
    if value <= gate:  # 越大越好
        return 0.0
    if value >= ideal:
        return 1.0
    return (value - gate) / (ideal - gate)


def _band_score(value: float, low: float, high: float, cap: float) -> float:
    """把「理想区间」映射到 0~1：区间**中心给满分**，两端降到 `EDGE_SCORE`，
    区间外线性衰减，`cap` 之外归零。

    为什么区间内不一律给满分：实测「放量上涨」的 80 只里，有 64 只同时落在
    涨幅 3~10% 且量比 2~6 的理想区间，于是全部并列 100 分 —— 排名就失去意义了。
    改成余弦钟形后中心唯一最高，既能分辨「教科书级」和「刚够格」，
    又不改变「落在区间里都算不错」的语义。

    **`high` 必须严格小于 `cap`。** 两者相等时区间上界恰好也是衰减终点，
    值正好落在那里会走 `value >= cap` 分支拿 0 分 —— 而那恰恰是最优值。
    这个坑我踩过 6 次（如「收盘从未跌破 MA20」得 0 分），单方向的打分一律用
    `_ramp`，别用这个。

    ⚠️ **「越接近区间中段越好」就把量本身传进来，别自己拼 `span - abs(x - mid)`。**
    那个量的最大值（正好落在中段时）是 `span`，而 band 的上界若写成 `span*0.8`，
    最优样本会被当成「过大」衰减 —— 分数变成**中间低、两边高**的 U 形，与「中段最好」
    正好相反，而且从结果里看不出来。缩量回踩与杯柄都这么错过（2026-09-27 修）。
    修完实测（1200 只样本）：缩量回踩信号 413 → 452 条，5/20/60 日超额基本不变；
    杯柄 11 → 13 条（样本太小，超额差异是噪声）。方向对、量级可控。
    """
    if value <= 0:
        return 0.0
    center = (low + high) / 2
    if low <= value <= high:
        return EDGE_SCORE + (1.0 - EDGE_SCORE) * math.cos(
            (value - center) / (high - low) * math.pi
        )
    if value < low:
        return EDGE_SCORE * (value / low)
    if value >= cap:
        return 0.0
    return EDGE_SCORE * (cap - value) / (cap - high)


def _ma_series(values: np.ndarray, window: int) -> np.ndarray | None:
    """滑动均值序列，长度 = len(values) - window + 1。数据不足返回 None。"""
    if values.size < window:
        return None
    cumulative = np.concatenate([[0.0], np.cumsum(values)])
    return (cumulative[window:] - cumulative[:-window]) / window


def _align(series: np.ndarray | None, window: int, length: int) -> np.ndarray:
    """把均线序列对齐到 K 线的索引，前面不足的部分填 NaN。

    对齐后 `result[i]` 就是第 i 根 K 线的均线值，省得每个形态各写一遍索引换算。
    """
    out = np.full(length, np.nan)
    if series is None:
        return out
    usable = min(series.size, length - window + 1)
    if usable > 0:
        out[window - 1 : window - 1 + usable] = series[:usable]
    return out


def _rolling(values: np.ndarray, window: int, mode: str) -> np.ndarray:
    """滑动窗口归约，**对齐到窗口右端**：`out[i]` 是 `values[i-window+1 … i]` 的归约值，
    前面不够 window 根的部分填 NaN。

    `mode` 取 `min` / `max` / `sum`，就是通达信的 `LLV` / `HHV` / `SUM`。窗口内的
    NaN 会传染（`min`/`max`/`sum` 都返回 NaN），这与 `_ma_series` 的口径一致：
    数据不够就是不够，不假装算得出来。
    """
    out = np.full(values.size, np.nan)
    if values.size < window:
        return out
    windows = np.lib.stride_tricks.sliding_window_view(values, window)
    if mode == "min":
        out[window - 1 :] = windows.min(axis=1)
    elif mode == "max":
        out[window - 1 :] = windows.max(axis=1)
    else:
        out[window - 1 :] = windows.sum(axis=1)
    return out


def _shift(values: np.ndarray, bars: int) -> np.ndarray:
    """`REF(values, bars)`：整体后移 `bars` 根，前面补 NaN。"""
    out = np.full(values.size, np.nan)
    if bars < values.size:
        out[bars:] = values[: values.size - bars]
    return out


def _cross(fast: np.ndarray, slow: np.ndarray) -> np.ndarray:
    """`CROSS(fast, slow)`：今天 `fast > slow` 且昨天 `fast <= slow`。

    NaN 参与比较恒为 False，所以预热段自然不算金叉。
    """
    out = np.zeros(fast.size, dtype=bool)
    out[1:] = (fast[1:] > slow[1:]) & (fast[:-1] <= slow[:-1])
    return out


def _barslast(flags: np.ndarray) -> np.ndarray:
    """`BARSLAST(flags)`：距上一次成立（含当根）的周期数。

    **从未成立过返回 `inf`。** 公式里它只用在「上次信号距今 > 冷却天数」这一处，
    `inf` 就等于「冷却已满足」—— 第一次出现当然该算信号，不该被冷却挡住。
    """
    out = np.full(flags.size, np.inf)
    last = -1
    for i in range(flags.size):
        if flags[i]:
            last = i
        if last >= 0:
            out[i] = i - last
    return out


def _rising(series: np.ndarray, lookback: int) -> bool:
    return series.size > lookback and series[-1] > series[-1 - lookback]


def _trailing_run(flags: np.ndarray) -> int:
    """从尾部往前数，连续的 True 有多少个。"""
    count = 0
    for flag in flags[::-1]:
        if not flag:
            break
        count += 1
    return count


def _safe_mean(values: np.ndarray) -> float:
    finite = values[np.isfinite(values)]
    return float(finite.mean()) if finite.size else 0.0


def _volume_ratio(bars: Bars, window: int) -> float:
    """当日成交量 / 前 window 日均量。"""
    if len(bars) < window + 1:
        return 0.0
    base = _safe_mean(bars.volume[-window - 1 : -1])
    return float(bars.volume[-1] / base) if base > 0 else 0.0


