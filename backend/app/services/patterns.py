def classify_phase(bars: Bars) -> PhaseVerdict | None:
    """整只票的阶段判定（移植自原型的 `classify_bars` + `_structure_brief`）。

    ⚠️ 与 `PATTERNS` 里的 `wudao_sample` / `wudao_start` **共用同一批判据**
    （`_wudao_is_sample` / `_wudao_is_diverge_or_dump` / `_wudao_day_geom`）——
    别在这里另写一套：两边分叉过一次，回测数字就不再代表生产。

    ⚠️ **但「共用判据」不等于「结果一致」**（2026-10-09 起，名单那侧多了两道过滤，
    两处都**故意**没写进这里）：
    - 名单只收**创业板 + 科创板**（`scan_patterns.is_wudao_board`），这里**全市场都判**
      —— 主板票也会被贴上「明天盯」，而名单里永远不会有它；
    - 名单出口另有一道 `_wudao_leave_ok`（收盘离开最高 ≤ 2.9%，见 §8.88.3）——
      它没并进 `_wudao_is_sample`，因为那个判据还被「洗完可盯」共用。
    实测 2026-09-28：这里判「明天盯」的 31 只里只有 6 只在名单。

    优先级在原型基础上把「走弱」提前到「刚有人气」之前：**启动 > 吵起来了 / 像出货 >
    明天盯 > 休息中 > 走弱 > 刚有人气 > 没动静**。这也是「明明冲高回落了、为什么没进明天盯」
    的答案 —— 它被更靠前的阶段占了（`_wudao_sample` 那边同样先过 `_wudao_is_diverge_or_dump`）。

    阈值都在文件顶部 `WUDAO_WAKE_*` / `WUDAO_DIGEST_*` / `WUDAO_WEAK_PCT` / `WUDAO_SILENT_VOL`
    那一段（2026-10-10 从函数体里抽出来集中的），别在下面的分支里再写裸数字。

    ⚠️ **对原型的四处修正 + 新增一档**（都做过实测，都是「标签与当日事实自相矛盾」）：

    1. **缩量大涨兜底**（2026-10-09）：`pct >= 9.5` 或（`pct >= 4` 且 `high_pct >= 6`）→ `wake`。
       原型直接按 `vol < 0.85` 判「没动静」，会把**缩量涨停 / 一字板**（量比常 0.3~0.8）
       说成「几乎没人气」（实测 4 只）。这类归 `wake`、文案另写（见 `thin_up` 分支）。
    2. **新增 `weak`（走弱）档**（2026-10-10）：`pct <= -3` → `weak`。原型没有「在跌」
       这一档，下跌只能落到「没动静 / 对不上」—— 实测 2026-09-28 前 1500 只里
       **102 只（6.8%）跌 3%~5%、量比 0.4~0.8 被判「没动静」**（文案还写着「几乎没人气」）。
       下界取 -3 与 `digest` 的下界**正好接上**，不留缝；这也把原先那条
       `pct <= -5 → unknown` 的兜底**收编**成了一个正式档（≤ -5 的大跌同样归 `weak`）。
    3. **`digest` 补下界**（2026-10-09）：`-3 <= pct <= 0`。原来只写 `pct <= 0`，跌停也会进
       「休息中」，与它自己的文案「涨跌不大，像在歇口气」直接冲突（实测 7 只、含 4 只跌停）。
    4. **`weak` 提到 `wake` 之前**（2026-10-10）：wake 里有条按 `high_pct >= 6` 判的支路，
       会把**高开 ≥6% 却收跌 ≤ -3%** 的票判成「刚有人气」（量回来了、价格也动了），与事实
       正好相反。让 `weak` 先判，这类一律归「走弱」。wake 与 thin 两条支路都要求 pct 为正，
       所以搬动不影响它们。

    `weak` 与 `digest` 的分工：`weak` **只看跌幅**（在跌就算走弱，放量缩量都算）；
    `digest` 是「涨过一截之后缩量歇气」（还要求近 5 日涨过 `WUDAO_DIGEST_RET5`）。
    所以两者不会抢：跌幅 ≤ -3 一律 `weak`，`digest` 只在 -3%~0 这一段、且前面刚涨过时才成立。
    """
    n = len(bars)
    if n < 25:
        return None
    i = n - 1
    vol, pct, close_pos, upper = _wudao_day_geom(bars, i)
    close = float(bars.close[i])
    high = float(bars.high[i])
    prev_close = float(bars.close[i - 1])
    yday_high = float(bars.high[i - 1])
    high_pct = (high / prev_close - 1.0) * 100.0 if prev_close else 0.0
    leave_high = (high - close) / max(high, 1e-9)
    ret_5 = (close / float(bars.close[i - 5]) - 1.0) * 100.0 if float(bars.close[i - 5]) else 0.0
    ret_20 = (
        (close / float(bars.close[i - 20]) - 1.0) * 100.0 if float(bars.close[i - 20]) else 0.0
    )
    yday_sample = _wudao_is_sample(bars, i - 1)
    today_sample = _wudao_is_sample(bars, i)
    broke_yday_high = high > yday_high and close >= yday_high * 0.98

    # ---- 决策链：从上往下问，**第一个成立的就是结论** ----
    # 顺序（= 优先级）：启动 > 吵/出货 > 明天盯 > 休息中 > 走弱 > 刚有人气 > 没动静 > 兜底。
    # 「走弱」刻意排在「刚有人气」**之前**（2026-10-10 调序）：高开 ≥6%（`high_pct` 达标）
    # 却收跌 ≤ -3% 的票，原先把 wake 排前面会判成「刚有人气」，与 wake 的语义相反。
    # 两个「兜底」都刻意放在**量能判据之前**：只看量的话，缩量涨停（量比 0.3~0.8）与
    # 缩量下跌都会掉进 `silent`、被说成「几乎没人气」，与当天涨停 / 大跌的事实冲突
    # （实测分别 4 只、102 只）。阈值见文件顶部 `WUDAO_WAKE_*` 那一段。
    thin_up = False
    if yday_sample and broke_yday_high and vol >= WUDAO_START_VOL and pct > 0:
        # 昨天是样板日、今天放量过昨高 → 启动
        phase = "start"
    elif _wudao_is_diverge_or_dump(bars, i):
        dump_like = vol >= WUDAO_DUMP_VOL and pct < WUDAO_DUMP_PCT and upper >= WUDAO_DUMP_UPPER
        # 原型是两条（吵起来了 / 像出货），标签要分开；判据在共用的那个函数里
        phase = "dump" if dump_like else "diverge"
    elif today_sample:
        # 今天自己就是样板日。`_wudao_is_sample` 内部要求 `pct >= -3`，
        # 所以下跌日走不到这里，不必另判
        phase = "sample"
    elif (
        WUDAO_DIGEST_PCT_LO <= pct <= 0
        and vol <= WUDAO_DIGEST_VOL
        and ret_5 >= WUDAO_DIGEST_RET5
    ):
        # 「休息中」= 前面涨过一截、今天缩量且涨跌不大。下界与「走弱」接上（见 docstring）
        phase = "digest"
    elif pct <= WUDAO_WEAK_PCT:
        # 「走弱」：**只看跌幅**，放量缩量都算（2026-10-10 新增，取代原先
        # `pct <= -5 → unknown` 的临时兜底 —— 那一版把 -5%~-3% 这段漏给了「没动静」）。
        # 排在这里是为了压住下面那条按 `high_pct` 判的 wake（见上「调序」说明）
        phase = "weak"
    elif vol >= WUDAO_WAKE_VOL and (pct >= WUDAO_WAKE_PCT or high_pct >= WUDAO_WAKE_HIGH_PCT):
        # 「刚有人气」：量回来了、价格也动了（今天是不是样板日已在上面拦掉，不必再判）
        phase = "wake"
    elif pct >= WUDAO_THIN_UP_PCT or (pct >= WUDAO_WAKE_PCT and high_pct >= WUDAO_WAKE_HIGH_PCT):
        # 缩量大涨兜底：涨幅够大但量没跟上（涨停 / 一字板常这样），仍归「刚有人气」，
        # 只是文案另写（`thin_up`）。能走到这里说明上面那条量能条件不成立。
        phase = "wake"
        thin_up = True
    elif vol < WUDAO_SILENT_VOL:
        phase = "silent"
    else:
        phase = "unknown"

    # ---- 结构简报：上影天数 / 左侧压力 / 计划 / 风险 ----
    recent_n = min(8, n)
    shadow_days = 0
    leave_sum = 0.0
    for k in range(n - recent_n, n):
        span = max(float(bars.high[k]) - float(bars.low[k]), 1e-9)
        up = (float(bars.high[k]) - max(float(bars.open[k]), float(bars.close[k]))) / span
        leave_sum += (float(bars.high[k]) - float(bars.close[k])) / max(float(bars.high[k]), 1e-9)
        if up >= 0.35:
            shadow_days += 1
    avg_leave = leave_sum / max(recent_n, 1)

    if shadow_days >= 5 and avg_leave >= 0.04:
        shadow_label = "天天长上影"
        shadow_text = (
            f"近 8 个交易日里有 {shadow_days} 天带明显长上影，平均离最高点约 {avg_leave:.0%}："
            "冲得猛、回得也猛，多空一直在打架。偶发一次可以是洗；天天都有更像分歧票，"
            "难拿、假突破也多。"
        )
        noisy = True
    elif shadow_days >= 5:
        shadow_label = "上影偏多"
        shadow_text = f"近 8 日有 {shadow_days} 天带上影，但回落幅度还不算极端。有点吵，仍可盯，仓位要小。"
        noisy = True
    elif shadow_days >= 3:
        shadow_label = "上影偏多"
        shadow_text = f"近 8 日有 {shadow_days} 天长上影，上方抛压不轻，过昨高后也要防冲高回落。"
        noisy = True
    elif upper >= 0.35:
        shadow_label = "今天有上影"
        shadow_text = "今天冲高没完全站住，更像「画样子」回落，不是单边封死。"
        noisy = False
    else:
        shadow_label = "上影不多"
        shadow_text = "最近不是天天冲高回落，形态相对干净一些。"
        noisy = False

    # 左侧压力 = 「近 60 / 120 日最高」。**只算 120 日这个就够** —— 60 日窗口是它的
    # 子集，取 120 日必然 ≥ 60 日，原先那两个变量再 max() 一次是纯冗余（2026-10-10 删）。
    # `n >= 30` 是本来的经验下限（不足两根月线就不谈左侧压力），保持原样：
    # 它意味着 25~29 根时 `left_high=None`、下面那几段压力文案整块不出现。
    left_high = float(np.max(bars.high[max(0, n - 120) :])) if n >= 30 else None
    low_20 = float(np.min(bars.low[n - 20 :]))
    ma20 = float(np.mean(bars.close[n - 20 :]))
    ma60 = float(np.mean(bars.close[n - 60 :])) if n >= 60 else None

    pressure_bits: list[str] = []
    if left_high and left_high > 0:
        dist = (left_high - close) / left_high * 100
        if dist >= 20:
            pressure_bits.append(
                f"离近几个月高点 {left_high:.2f} 还有约 {dist:.0f}%，上方有一段下跌留下的套牢区（左侧压力）。"
            )
        elif dist >= 10:
            pressure_bits.append(f"上方不远有前高/套牢带（约 {left_high:.2f}），冲过去容易滞涨。")
    if ma20 and close < ma20 * 0.98 and ret_5 > 0:
        pressure_bits.append(f"价格还在 20 日线（约 {ma20:.2f}）下方附近抬头，反弹时容易碰到均线压力。")
    if ma60 and close >= ma60 * 0.97 and close <= ma60 * 1.05:
        pressure_bits.append(f"正蹭着 60 日线一带（约 {ma60:.2f}），这里常有多空分歧。")
    if low_20 and left_high and (close - low_20) / max(left_high - low_20, 1e-9) < 0.45 and ret_20 < 15:
        pressure_bits.append("更像底部反抽探路，不是主升中段；过昨高只是短线确认，别当一飞冲天。")

    # 样板质量：回落温和 + 冲高没太猛 → 更像「干净样板」
    mild_pullback = avg_leave <= 0.045 and high_pct <= 10
    if phase == "sample" and mild_pullback and vol >= 1.5 and not (shadow_days >= 5 and avg_leave >= 0.05):
        fit_label, prefer = "更像你要的", 3
        fit_text = "冲高回落 + 有量，回落幅度相对温和，比较像「先画出样子再等确认」。"
        if pressure_bits:
            fit_text += " 但上方有左侧压力，过昨高后别幻想直奔前高。"
    elif phase == "sample" and noisy and avg_leave >= 0.05:
        fit_label, prefer = "勉强算样板，但偏吵", 1
        fit_text = (
            "也冲高回落了所以进了「明天盯」，但最近老是大幅冲高回落，质量不如干净样板。"
            "可观察，不必跟更干净的票抢仓。"
        )
    elif phase == "sample" and noisy:
        fit_label, prefer = "能盯，略吵", 2
        fit_text = "符合「明天盯」，但上影偏多。能盯，仓位要小；有更干净的票时优先别人。"
    elif phase == "sample":
        fit_label, prefer = "能盯，中等", 2
        fit_text = "符合「明天盯」的基本样子，质量中等。过今高可小仓，不过就空着。"
    elif phase == "start" and not noisy:
        fit_label, prefer = "启动较干净", 3
        fit_text = "过昨高且量跟上了。买点是刚过那一下；收盘后才看见大涨贴板，明天别追。"
    elif phase == "start":
        fit_label, prefer = "启动但带分歧", 1
        fit_text = "算启动，但上影/波动大，只能极小仓或等回踩分时均价，别追尖。"
    elif phase in ("diverge", "dump"):
        fit_label, prefer = "不像启动模板", 0
        fit_text = "现在是刹车灯，不是油门。别当样板/启动去追。"
    elif phase == "weak":
        fit_label, prefer = "在往下走", 0
        fit_text = "不符合任何动手模板，而且今天在跌。别当机会看，等它重新走出样板日。"
    else:
        fit_label, prefer = "还没到动手档", 0
        fit_text = "还没走到「明天盯 / 明天预案」。先放着，别空耗仓位。"

    if phase == "sample":
        plan_text = (
            f"今天不买。下一个交易日盯今高 {high:.2f}：刚过可小仓；不过就空着；"
            "过了又快速掉回今高下，当假突破。"
        )
        if noisy:
            plan_text += " 这只偏吵，仓位要比更干净的票更小，甚至可以只观察不做。"
        if pressure_bits:
            plan_text += " 过了也不要幻想直奔前高，碰到左侧压力滞涨就减。"
    elif phase == "start":
        plan_text = (
            f"买点是盘中刚过昨高 {yday_high:.2f}。若你是收盘后才看到、已经大涨，"
            "默认下一个交易日不追。"
        )
    elif phase in ("diverge", "dump"):
        plan_text = "只减不加。没仓就别上车。"
    elif phase == "digest":
        plan_text = "有仓用分时均价：跌破减/清。没仓别抄。"
    elif phase == "weak":
        plan_text = "有仓：反抽不过昨高就减；没仓：不接飞刀。"
    else:
        plan_text = WUDAO_PHASE_DO[phase]

    if phase == "start":
        text = f"昨天冲高回落过，今天已经过了昨高 {yday_high:.2f}，量比 {vol:.2f}。"
    elif phase == "diverge":
        text = f"量很大（量比 {vol:.2f}），但冲高没站住（上影约 {upper:.2f}），多空在打架。"
    elif phase == "dump":
        text = f"量不小（量比 {vol:.2f}），价格却涨不动、冲完就回，更像有人在出。"
    elif phase == "sample":
        text = (
            f"今天冲过大约 {high_pct:.1f}% 又收回来，量比 {vol:.2f}；"
            f"记下今高 {high:.2f}，明天过了再买，不过就空着。"
        )
    elif phase == "digest":
        text = f"前几天已经拉过一截，今天量缩（量比 {vol:.2f}）、涨跌不大，像在歇口气。"
    elif phase == "weak":
        text = f"今天跌 {pct:.1f}%、量比 {vol:.2f}，在走弱；没重新走出样板日之前不值得看。"
    elif phase == "wake":
        if thin_up:
            text = (
                f"今天涨 {pct:.1f}%、量比 {vol:.2f} —— 量能没跟上（封板/一字也会锁着量）。"
                "别按「放量启动」看待，等明天看量能能不能接上。"
            )
        else:
            text = f"量开始回来（量比 {vol:.2f}），价格也动了，但还没走出「冲高再回落」的样子。"
    elif phase == "silent":
        text = f"量比只有 {vol:.2f}，几乎没人气；这种票很少第二天就起飞。"
    else:
        text = f"量比 {vol:.2f}，涨跌 {pct:.2f}%，暂时对不上模板。"

    action = WUDAO_PHASE_DO[phase]
    if phase == "start" and (upper >= 0.28 or close_pos < 0.65):
        text += " 今天上影不小，即使算可买也只能极小仓，冲高先减。"
        action = "极小仓；更稳是等回踩分时均价"

    risk_bits: list[str] = []
    if phase == "weak":
        risk_bits.append("今天在往下走，别在下跌里找买点")
    if pressure_bits:
        risk_bits.append("左侧/均线压力，冲高易滞涨")
    if noisy:
        risk_bits.append("反复长上影，假突破多")
    if ret_5 >= 25:
        risk_bits.append(f"近 5 日已涨约 {ret_5:.0f}%，别当起涨点猛加")
    if vol >= 3 and close_pos < 0.7:
        risk_bits.append("爆量却收不在高位，分歧大")
    if not risk_bits:
        risk_bits.append("不过昨高不要进；破分时均价要会走")

    if pressure_bits:
        pressure_label, pressure_text = "左侧有压力", " ".join(pressure_bits[:3])
    else:
        pressure_label = "上方压力不明显"
        pressure_text = "按近期结构看，没有特别扎眼的左侧大套牢墙；仍要用分时均价管风险。"

    watch_price = high if phase == "sample" else (yday_high if phase == "start" else None)

    return PhaseVerdict(
        phase=phase,
        label=WUDAO_PHASE_LABELS[phase],
        action=action,
        text=text,
        fit_label=fit_label,
        fit_text=fit_text,
        prefer=prefer,
        shadow_label=shadow_label,
        shadow_text=shadow_text,
        pressure_label=pressure_label,
        pressure_text=pressure_text,
        plan_text=plan_text,
        risk_text="；".join(risk_bits) + "。",
        watch_price=round(watch_price, 2) if watch_price else None,
        metrics={
            "close": round(close, 2),
            "pct_chg": round(pct, 2),
            "high_pct": round(high_pct, 1),
            "vol_ratio": round(vol, 2),
            "close_pos": round(close_pos, 2),
            "upper_shadow": round(upper, 2),
            "leave_high": round(leave_high, 4),
            "ret_5": round(ret_5, 1),
            "ret_20": round(ret_20, 1),
            "yday_high": round(yday_high, 2),
            "today_high": round(high, 2),
            "ma20": round(ma20, 2) if ma20 else None,
            "left_high": round(left_high, 2) if left_high else None,
            "shadow_days": shadow_days,
        },
    )


def _wudao_day_volume_ratio(bars: Bars, i: int) -> float:
    """第 i 根的**量比** = 当日量 ÷ 近 20 日均量（不含当日），口径与 `_wudao_day_geom` 一致。

    与悟道之路的 `enrich` 有一处小差别：它 `vol_ma20 = volume.rolling(20).mean()` 是
    **含当日**的，我们是不含当日。在 1.3~1.5 这些门槛附近两者差不到 3%
    （解一下方程：要打到量比 1.3，含当日口径其实只要 1.32 倍的「前 20 日均量」），
    所以 2026-09-23 那次对账两边计数才会完全一致。**站内一律用这一套**
    （含当日的写法会让一根爆量把分母自己抬高、量比反而变小，不同口径混用比统一更重要）。
    """
    if i < 20:
        return 0.0
    base = _safe_mean(bars.volume[i - 20 : i])
    return float(bars.volume[i] / base) if base > 0 else 0.0


def _wudao_wash2(bars: Bars) -> Signal | None:
    """洗完 → 明天可进（悟道之路「辉宾选股2」，2026-10-08 移植）。

    四段结构：**样板日 → 启动日 → 今日洗盘 → 明天放量过「洗高」**。
    前两段的判定与「明天盯 / 明天预案」**完全同一套**（复用 `_wudao_is_sample` 与同组数字），
    第三段是本形态新增的：洗盘日要守住两个锚点（启动低 / 样板高）、收盘温和、不是继续主升。

    数字全部照抄 `yangban-desk/app/pattern_wash2.py`（commit fe32f80），逐条见文件上方常量。
    它的纪律（`选股逻辑说明.txt` 六段口诀）：**今天是洗盘日 → 只观察记账，不追尖、不加仓**；
    明天盘中放量过洗高再小仓；缩量阴过洗高不算；破启动低（或放量破样板高且收不回）作废。

    出参把两条线一起给前端：`watch_high`（明天要过的线）、`start_low`（作废线）。
    """
    if len(bars) < WUDAO_WASH_MIN_BARS:
        return None
    i = len(bars) - 1
    s, st, w = i - 2, i - 1, i  # 样板 / 启动 / 今日洗盘

    # ① 样板日：与「明天盯」共用 `_wudao_is_sample`（但**不含**吵了/出货的否决 ——
    #    那道 `_wudao_is_diverge_or_dump` 只加在「明天盯 / 明天预案」两个出口，这里没有）
    if not _wudao_is_sample(bars, s):
        return None
    sample_high = float(bars.high[s])

    # ② 启动日：今过昨高 + 收盘站在昨高之上 + 量比达标 + 收红
    start_pct = float(bars.pct_chg[st])
    start_vol = _wudao_day_volume_ratio(bars, st)
    if float(bars.high[st]) <= sample_high:
        return None
    if float(bars.close[st]) < sample_high * 0.98:
        return None
    if start_vol < WUDAO_START_VOL or start_pct <= 0:
        return None

    # ③ 今日洗盘：四个锚点条件
    start_close = float(bars.close[st])
    start_low = float(bars.low[st])
    wash_open = float(bars.open[w])
    wash_close = float(bars.close[w])
    wash_low = float(bars.low[w])
    wash_high = float(bars.high[w])
    wash_pct = float(bars.pct_chg[w])
    start_volume = float(bars.volume[st])
    wash_volume = float(bars.volume[w])
    vol_vs = wash_volume / start_volume if start_volume > 0 else 1.0

    if wash_low < start_low * 0.995:  # 破启动低
        return None
    if wash_close < sample_high * 0.98:  # 掉下样板高
        return None
    if abs(wash_pct) > WUDAO_WASH_MAX_ABS_PCT:
        return None
    body_pct = abs(wash_close - wash_open) / max(start_close, 1e-9) * 100.0
    if body_pct > WUDAO_WASH_MAX_BODY_PCT and wash_pct > 2:  # 大阳续涨不算洗
        return None
    if wash_close > start_close * WUDAO_WASH_MAX_VS_START_CLOSE:
        return None

    # 打分：越干净的洗盘分越高。干净的判据与它一致 —— |洗盘涨跌|≤2% 且 量/启动 ≤1.05
    clean = abs(wash_pct) <= 2.0 and vol_vs <= 1.05
    score = 62.0 if clean else 54.0
    score += _band_score(start_vol, WUDAO_START_VOL, 3.0, 8.0) * 18
    # 洗盘越温和越高（单方向）。原来是 `_band_score(abs(wash_pct), 0.0, 3.0, 8.0)`：
    # `_band_score` 对 value<=0 直接给 0 分 —— 恰好把最温和的「平盘洗」打成 0，
    # 与注释相反（2026-10-10 改成 `_gate_score`）。上面已否决 |wash_pct|>3。
    score += _gate_score(abs(wash_pct), WUDAO_WASH_MAX_ABS_PCT, 0.0) * 12
    if vol_vs <= 1.05:
        score += 8

    return Signal(
        "wudao_wash2",
        score,
        # 两条线：明天要过洗高才进；破了启动低就作废
        {"watch_high": wash_high, "start_low": start_low, "breakout": wash_high},
        {
            "sample_high": round(sample_high, 2),
            "start_low": round(start_low, 2),
            "start_close": round(start_close, 2),
            "start_pct": round(start_pct, 2),
            "start_vol_ratio": round(start_vol, 2),
            "wash_high": round(wash_high, 2),
            "wash_pct": round(wash_pct, 2),
            "wash_vol_vs_start": round(vol_vs, 2),
            "clean": clean,
        },
    )


# ------------------------------------------------- 悟道之路 · 强达型（2026-10-08 移植）


def _ret_pct(bars: Bars, index: int, back: int) -> float:
    """第 index 根相对 `back` 个交易日前的涨幅（%）。`back=5` 就是悟道的 `ret_5`。"""
    base_index = index - back
    if base_index < 0:
        return 0.0
    base = float(bars.close[base_index])
    return (float(bars.close[index]) / base - 1.0) * 100.0 if base > 0 else 0.0


def _pile_wash_phase(bars: Bars) -> tuple[str, dict] | None:
    """强达型的阶段判定，返回 `(阶段, 指标)`。

    逐行照抄 `yangban-desk/app/pile_wash.py::score_pile_wash`（commit fe32f80），
    只把 pandas 的 `iloc` 切片换成 numpy 下标：

    1. 在**最近 55 根**里滑窗找「放量拉升」段（宽度 5~12、段内最高 / 前基 ≥16%、
       段末收盘 / 前基 ≥10%、段均量 / 前段均量 ≥1.35、阳线数 ≥ max(2, 宽度//3)），
       给每个候选打分（涨幅×0.45 + 放量×12 + 收盘涨幅×0.25 + 阳线数；收盘位置偏低 ×0.7；
       拉升后已经缩量的加分），取最高分的那个窗口
    2. 判前段堆量（≥1.25 倍、不是单边暴跌、振幅 <38%）
    3. 判后段缩量洗盘（量 ≤ 拉升期 0.72、守住前基 ×1.05、回吐 <0.62、振幅 ≤28%）
    4. 洗盘成立再看形态走到哪：贴着/越过洗盘高 → `ready`；已远离且 5 日大涨 → `gone`；
       回撤过大 → `gone`；其余 → `wash`

    ⚠️ 它那套的 `pile`（堆量吸筹中，含「只有堆量、还没拉升」那条 `_maybe_pile_only` 分支）
    我们**不出信号**，直接返回 None —— 纪律是「只观察，别动手」。
    """
    n = len(bars.close)
    if n < PILE_MIN_BARS:
        return None
    off = max(0, n - PILE_LOOK_BARS)  # look 的起点（绝对下标）
    total = n - off  # look 的长度
    if total < 30:
        return None

    def mean_vol(start: int, end: int) -> float:
        """look 上 `[start, end]` 闭区间的均量（绝对下标）。"""
        lo, hi = off + start, off + end + 1
        return float(np.mean(bars.volume[lo:hi])) if hi > lo else 0.0

    best: tuple | None = None
    for end in range(8, total):
        for width in PILE_SURGE_WIDTHS:
            start = end - width + 1
            if start < 5:
                continue
            pre_start = max(0, start - 18)
            if start - pre_start < PILE_PRE_MIN_BARS:
                continue
            base = float(bars.close[off + start - 1])
            if base <= 0:
                continue
            peak = float(np.max(bars.high[off + start : off + end + 1]))
            end_close = float(bars.close[off + end])
            surge_ret = (peak / base - 1.0) * 100.0
            close_ret = (end_close / base - 1.0) * 100.0
            if surge_ret < PILE_SURGE_MIN_RET or close_ret < PILE_SURGE_MIN_CLOSE_RET:
                continue
            vol_s = mean_vol(start, end)
            vol_p = mean_vol(pre_start, start - 1) or 1.0
            vol_lift = vol_s / vol_p
            if vol_lift < PILE_SURGE_MIN_VOL_LIFT:
                continue
            window_close = bars.close[off + start : off + end + 1]
            window_open = bars.open[off + start : off + end + 1]
            yang = int(np.sum(window_close >= window_open))
            if yang < max(2, width // 3):
                continue
            lowest = float(np.min(bars.low[off + start : off + end + 1]))
            close_pos = (end_close - lowest) / max(peak - lowest, 1e-9)
            score = surge_ret * 0.45 + vol_lift * 12 + close_ret * 0.25 + yang
            if close_pos < 0.55:
                score *= 0.7
            # 更偏向「拉升后还有缩量段」的窗口（强达那种中段），避免只咬住最近的主升尖
            after_len = total - 1 - end
            if after_len >= 4:
                tail_end = min(end + 14, total - 1)
                wr = mean_vol(end + 1, tail_end) / max(vol_s, 1.0)
                if wr <= PILE_WASH_MAX_VOL_RATIO:
                    score += 18 + (PILE_WASH_MAX_VOL_RATIO - wr) * 20
                elif wr <= 0.9:
                    score += 6
            else:
                score *= 0.85
            cand = (score, start, end, surge_ret, vol_lift, base, peak)
            if best is None or cand[0] > best[0]:
                best = cand

    if best is None:
        return None  # 没找到拉升窗口 → 只有可能落在「堆量」那一档，我们不出信号

    _, s0, s1, surge_ret, vol_lift, base, surge_high = best
    last_i = total - 1

    # —— ① 拉升前是否有堆量 ——
    pile_ok = False
    pile_ratio: float | None = None
    pre_start = max(0, s0 - 22)
    pre_len = s0 - pre_start
    if pre_len >= 10:
        quiet_end = max(5, pre_len // 2)  # 相对 pre 的前半段
        quiet_vol = mean_vol(pre_start, pre_start + quiet_end - 1) or 1.0
        pile_vol = mean_vol(pre_start + quiet_end, s0 - 1)
        pile_ratio = pile_vol / quiet_vol
        pre_ret = (
            float(bars.close[off + s0 - 1]) / float(bars.close[off + pre_start]) - 1.0
        ) * 100.0
        pre_range = (
            float(np.max(bars.high[off + pre_start : off + s0]))
            / max(float(np.min(bars.low[off + pre_start : off + s0])), 1e-9)
            - 1.0
        ) * 100.0
        pile_ok = (
            pile_ratio >= PILE_PILE_MIN_RATIO
            and pre_ret > PILE_PILE_MIN_PRE_RET
            and pre_range < PILE_PILE_MAX_PRE_RANGE
        )

    # —— ② 拉升后是不是缩量洗盘 ——
    wash_days = last_i - s1
    phase = "surge"
    wash_vol_ratio: float | None = None
    wash_high: float | None = None
    wash_low: float | None = None
    giveback: float | None = None
    if wash_days >= 3:
        wash_end = min(s1 + 18, last_i)  # 洗盘超过 18 根只取前 18 根
        vol_surge = mean_vol(s0, s1) or 1.0
        vol_wash = mean_vol(s1 + 1, wash_end)
        wash_vol_ratio = vol_wash / vol_surge
        wash_high = float(np.max(bars.high[off + s1 + 1 : off + wash_end + 1]))
        wash_low = float(np.min(bars.low[off + s1 + 1 : off + wash_end + 1]))
        peak_close = float(np.max(bars.close[off + s0 : off + s1 + 1]))
        wash_close = float(bars.close[off + wash_end])
        giveback = (peak_close - wash_close) / max(peak_close - base, 1e-9)
        held = wash_close >= base * PILE_WASH_KEEP_ABOVE_BASE
        not_dump = giveback < PILE_WASH_MAX_GIVEBACK
        vol_shrink = wash_vol_ratio <= PILE_WASH_MAX_VOL_RATIO
        tight = (wash_high / max(wash_low, 1e-9) - 1.0) * 100.0 <= PILE_WASH_MAX_RANGE_PCT

        if vol_shrink and held and not_dump and tight:
            phase = "wash"
            close = float(bars.close[n - 1])
            vol_ratio = _wudao_day_volume_ratio(bars, n - 1)
            pct_now = float(bars.pct_chg[n - 1])
            near = close >= wash_high * PILE_READY_NEAR
            broke = close > wash_high and last_i > s1
            if broke and close > wash_high * PILE_GONE_ABOVE and _ret_pct(
                bars, n - 1, 5
            ) > PILE_GONE_RET5:
                phase = "gone"
            elif broke or (near and vol_ratio >= PILE_READY_MIN_VOL and pct_now > 0):
                phase = "ready"
        elif giveback > 0.75:
            phase = "gone"

    if last_i <= s1:  # 仍在拉升窗内
        phase = "surge"

    metrics = {
        "pile_ok": pile_ok,
        "pile_ratio": pile_ratio,
        "surge_ret": surge_ret,
        "vol_lift": vol_lift,
        "surge_high": surge_high,
        "wash_days": wash_days,
        "wash_vol_ratio": wash_vol_ratio,
        "wash_high": wash_high,
        "wash_low": wash_low,
        "giveback": giveback,
        # 位置维度（2026-10-09 加）：现价 / MA60。见 PILE_WASH_MIN_POS_MA60
        "pos_ma60": float(bars.close[n - 1])
        / max(float(np.mean(bars.close[max(0, n - 60) : n])), 1e-9),
        "surge_start_gap": last_i - s1,  # 拉升段结束距今几根（诊断用）
    }
    return phase, metrics


def _pile_wash_signal(bars: Bars, want: str) -> Signal | None:
    """强达型两个形态的公共出口：只在阶段等于 `want` 时出信号。"""
    result = _pile_wash_phase(bars)
    if result is None:
        return None
    phase, m = result
    if phase != want or m["wash_high"] is None:
        return None
    # 位置门槛（2026-10-09 加）：只卡「缩量洗盘中」这一格 —— 单看结构它就是
    # 全市场平均（安静型标签没有筛选力）。见 PILE_WASH_MIN_POS_MA60 的实测数字。
    if want == "wash" and float(m["pos_ma60"]) < PILE_WASH_MIN_POS_MA60:
        return None

    wash_high = float(m["wash_high"])
    wash_low = float(m["wash_low"]) if m["wash_low"] is not None else None
    shrink = m["wash_vol_ratio"]
    # 打分：洗后可盯（要动手的）> 缩量洗盘中（主观察）。缩得越干净、前面有堆量，分越高
    score = 68.0 if want == "ready" else 56.0
    if shrink is not None:
        score += min(14.0, max(0.0, (PILE_WASH_MAX_VOL_RATIO - float(shrink)) * 40.0))
    if m["pile_ok"]:
        score += 6.0
    score = min(score, 95.0)

    levels: dict[str, float] = {"breakout": wash_high, "wash_high": wash_high}
    if wash_low is not None:
        levels["wash_low"] = wash_low
    detail: dict[str, float | int] = {
        "surge_ret": round(float(m["surge_ret"]), 2),
        "vol_lift": round(float(m["vol_lift"]), 2),
        "wash_days": int(m["wash_days"]),
        "pile_ok": int(bool(m["pile_ok"])),
    }
    if shrink is not None:
        detail["wash_vol_ratio"] = round(float(shrink), 2)
    if m["giveback"] is not None:
        detail["giveback"] = round(float(m["giveback"]), 3)
    if m["pile_ratio"] is not None:
        detail["pile_ratio"] = round(float(m["pile_ratio"]), 2)
    return Signal(f"pile_wash_{want}", score, levels, detail)


def _pile_wash_ready(bars: Bars) -> Signal | None:
    """洗后可盯：缩量洗完，现价刚贴近/越过洗盘高 —— 盘中放量过洗盘高可小仓试。

    判据见 `_pile_wash_phase`；「过洗盘高」那条线在 `key_levels["breakout"]`。
    """
    return _pile_wash_signal(bars, "ready")


def _pile_wash_wash(bars: Bars) -> Signal | None:
    """缩量洗盘中：拉升后横着、量掉回拉升期 —— 主观察，记下洗盘高，缩量别乱砍。

    2026-10-09 起多一道**位置门槛**（现价 ≥ MA60×1.08）：单看结构它等于全市场平均，
    只在「现价站在中期均线上方」这一半里才留，理由与实测见 `PILE_WASH_MIN_POS_MA60`。
    """
    return _pile_wash_signal(bars, "wash")


