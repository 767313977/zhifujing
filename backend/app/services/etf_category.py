# 去掉结尾代表「这是只基金」的词。循环两次是因为「XXETF联接基金」这种叠法
_TAIL = re.compile(r"(ETF|基金|联接|LOF)$")

UNKNOWN = "其他"


def classify(name: str | None) -> str:
    """ETF 名称 → 分类。归不出来时返回「其他」。"""
    text = (name or "").strip()
    if not text:
        return UNKNOWN
    # 先摘掉管理人名字，避免「招商中证白酒」里的「招商」干扰、
    # 也避免「华安黄金」里的管理人名和主题词混在一起
    for house in HOUSES:
        text = text.replace(house, "")
    for _ in range(2):
        text = _TAIL.sub("", text)
    text = text.strip()
    # 去掉管理人之后可能什么都不剩（比如「ETF基金」这种），用原名再试一次
    for candidate in (text, (name or "").strip()):
        for label, words in RULES:
            for word in words:
                if word in candidate:
                    return label
    return UNKNOWN
