"""涨跌幅限制（涨停 / 跌停）的口径。

**为什么不能用一个固定阈值。** 各板块的限制不一样，一刀切 9.5% 会两头出错：
把创业板 / 科创板（20cm）的 +10% 大阳线**误判成涨停**，又会漏掉主板 ST（5cm）的涨停。

| 类别 | 代码前缀 | 限制 |
| --- | --- | --- |
| 沪深主板 / 中小板 | 600 / 601 / 603 / 605、000 / 001 / 002 / 003 | 10% |
| 创业板 | 300 / 301 / 302 | 20% |
| 科创板 | 688 / 689 | 20% |
| 北交所 | 43 / 83 / 87 / 88、920 | 30% |
| 主板 ST / *ST | 主板前缀 + 名称含 ST | 5% |

⚠️ 创业板 / 科创板的 ST **仍是 20%**（2020 年改革后没有 5cm 那一档），所以 ST 只改变
主板的判定 —— 这两类直接返回 20%，不看名称。

## 判定：两个条件缺一不可

1. **涨幅达到限制**（留 0.5 余量，见下）
2. **收盘价就是当日最高价** —— 涨停的含义是「收盘封在涨停价上」，而涨停价必然是当日最高价。

第 2 条不能省：只用涨幅的话，一批**炸板**的票会被标成涨停（盘中摸到涨停、收盘掉到 +9.6%，
主板很常见），而那恰恰是打板的人最不想看错的。加上它之后，判定对**不复权与复权序列同样成立**
—— 复权是整段同乘一个系数，「收盘 = 最高」这个相对关系不变。

**跌停完全对称**（`is_limit_down`）：跌幅达到限制（向下）且**收盘价就是当日最低价**
—— 收盘封在跌停价上，而跌停价必然就是当日最低价。同样要防「盘中砸到跌停又拉回来」的
假跌停。余量与容差共用下面那组常量，方向相反而已。

## 判定阈值为什么留 0.5 的余量

判据是 `pct_chg >= 限制 − 0.5`，**不是「>= 限制」**：涨停价要**四舍五入到分**，低价股的
实际涨停涨幅会低于名义值 —— 3.33 元的票涨停价 3.66 元，实际只有 **+9.91%**；越低价偏离越大
（1 元附近约 0.5%），5 元以上不到 0.1%。不留余量就会漏掉一批真实的涨停。

这与形态引擎里 `patterns.LS_LIMIT_PCT = 9.5` 的**阈值**一致，区别是这里按板块取限制
（那个常量是「全市场一律 9.5%」，因为它的用途是筛形态、不吃板块差异）。

## 新股上市初期

创业板 / 科创板前 5 个交易日、主板首日（2023 全面注册制后主板新股也是前 5 日）**没有涨跌幅
限制**，那几天不该算涨跌停。这里**不特判**，所以这档会**漏进来一点**：

阈值只卡一侧（`pct >= 限制 − 0.5` / `pct <= −(限制 − 0.5)`，**没有上限**），于是新股不限幅那
几天里**恰好收在最高 / 最低价上**的会撞进判据。实测 2026-08-28~09-23 一个窗口内，跌停侧
162 个判定里有 1 个是这来的（603448 天博智能 2026-09-08 收 −16.1%、收 = 最低，是上市初期
的不限幅日）。要修就得引入「上市天数」或加一侧上限，为一个低于 1% 的误标不值当 ——
但**别再说「阈值法对它们不成立所以不会误标」**（这句原话是错的，2026-09-26 实测推翻）。

另有一类**边界误标**同样来自「只卡一侧」：收盘价是当日最低、但落在跌停价**上方 1 分**
（如 6.12 → 跌停价 5.51，实收 5.52），其实没封在板上。同一窗口里 162 个有 3 个。涨停侧
对称地有同一问题（收 = 最高但离涨停价 1 分）。真要精确得拿「前收盘 × 限幅四舍五入到分」
去比价格，那要改 `is_limit_up` 的既有口径 —— 见 §9 待定项，别只改一侧。
"""

CHINEXT_PREFIXES = ("300", "301", "302")
STAR_PREFIXES = ("688", "689")
BSE_PREFIXES = ("43", "83", "87", "88", "920")

# 涨停判定留的余量：涨停价四舍五入到分，低价股的实际涨停涨幅低于名义值（见模块说明）
_LIMIT_SLACK = 0.5

# 「收盘 = 最高」的容差（元）。两个值来自同一个数据源、封板时逐位相同，
# 留半个分只是防浮点噪声
_CLOSE_IS_HIGH_TOL = 0.005


def limit_pct(code: str, name: str | None = None) -> float:
    """这只票当日的涨跌幅限制（百分数，如 10.0 / 20.0 / 5.0）。

    名称只用来认 ST，且**只对主板生效** —— 创业板 / 科创板的 ST 也是 20%。
    """
    c = str(code or "").strip().zfill(6)
    if c.startswith(CHINEXT_PREFIXES) or c.startswith(STAR_PREFIXES):
        return 20.0
    if c.startswith(BSE_PREFIXES):
        return 30.0
    if name and "ST" in name.upper():
        return 5.0
    return 10.0


def is_limit_up(
    pct_chg: float | None,
    close: float | None,
    high: float | None,
    code: str,
    name: str | None = None,
) -> bool:
    """这一天是不是收盘涨停。涨跌幅 / 价格缺失（停牌等）一律 False。"""
    if pct_chg is None or close is None or high is None:
        return False
    if pct_chg < limit_pct(code, name) - _LIMIT_SLACK:
        return False
    # 收盘封板 ⇒ 收盘价即当日最高价（见模块说明第 2 条）
    return close >= high - _CLOSE_IS_HIGH_TOL


def is_limit_down(
    pct_chg: float | None,
    close: float | None,
    low: float | None,
    code: str,
    name: str | None = None,
) -> bool:
    """这一天是不是收盘跌停。与 `is_limit_up` 完全对称，只是方向相反。

    跌幅 / 价格缺失（停牌等）一律 False。余量与容差都共用同一组常量 —— 跌停价的
    四舍五入到分对低价股同样成立，只是误差朝另一个方向。
    """
    if pct_chg is None or close is None or low is None:
        return False
    if pct_chg > -(limit_pct(code, name) - _LIMIT_SLACK):
        return False
    # 收盘封板 ⇒ 收盘价即当日最低价（见模块说明）
    return close <= low + _CLOSE_IS_HIGH_TOL
